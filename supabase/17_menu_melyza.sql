insert into public.menu_options (menu_item_id, name, extra_price, is_active)
select m.id, s.nom, s.prix, true
  from sups s
  cross join resto r
  join public.menu_items m on m.restaurant_id = r.id and m.name = s.plat
 where not exists (
   select 1 from public.menu_options o where o.menu_item_id = m.id and o.name = s.nom
 );


-- ---------------------------------------------------------- VÉRIFICATION
select r.name as restaurant,
       count(distinct m.id) as plats,
       count(distinct v.id) as formats,
       count(distinct o.id) as supplements
  from public.restaurants r
  left join public.menu_items m on m.restaurant_id = r.id
  left join public.menu_variants v on v.menu_item_id = m.id
  left join public.menu_options o on o.menu_item_id = m.id
 where r.name ilike '%melyza%'
 group by r.name;

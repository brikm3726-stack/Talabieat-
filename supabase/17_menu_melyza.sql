select r.id, c.id, p.nom, p.descr, p.prix, p.ordre, true
  from plats p
  cross join resto r
  join public.categories c on c.slug = p.cat
 where not exists (
   select 1 from public.menu_items m where m.restaurant_id = r.id and m.name = p.nom
 );


